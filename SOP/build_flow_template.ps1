function Fill-Sheet($ws, $title, $note, $headers, $rows, $widths, $editCols) {
    $ws.Cells.Font.Name = 'Arial'
    $ws.Cells.Font.Size = 10
    $ws.Cells.Item(1, 1).Value2 = $title
    $ws.Cells.Item(1, 1).Font.Size = 14
    $ws.Cells.Item(1, 1).Font.Bold = $true
    $ws.Cells.Item(2, 1).Value2 = $note
    $ws.Cells.Item(2, 1).Font.Italic = $true
    $ws.Cells.Item(2, 1).Font.Color = 0x595959
    $r0 = 4
    for ($c = 0; $c -lt $headers.Count; $c++) {
        $cell = $ws.Cells.Item($r0, $c + 1)
        $cell.Value2 = $headers[$c]
        $cell.Font.Bold = $true
        $cell.Font.Color = 0xFFFFFF
        $cell.Interior.Color = $head
        $ws.Columns.Item($c + 1).ColumnWidth = $widths[$c]
    }
    for ($r = 0; $r -lt $rows.Count; $r++) {
        for ($c = 0; $c -lt $rows[$r].Count; $c++) {
            $ws.Cells.Item($r0 + 1 + $r, $c + 1).Value2 = [string]$rows[$r][$c]
        }
    }
    $last = $r0 + $rows.Count
    $rng = $ws.Range($ws.Cells.Item($r0, 1), $ws.Cells.Item($last, $headers.Count))
    $rng.WrapText = $true
    $rng.VerticalAlignment = -4160          # 靠上
    $rng.Borders.LineStyle = 1
    $rng.Borders.Color = 0xBFBFBF
    foreach ($ec in $editCols) {
        $ws.Range($ws.Cells.Item($r0 + 1, $ec), $ws.Cells.Item($last + 10, $ec)).Interior.Color = $yellow
        $ws.Range($ws.Cells.Item($r0 + 1, $ec), $ws.Cells.Item($last + 10, $ec)).Borders.LineStyle = 1
        $ws.Range($ws.Cells.Item($r0 + 1, $ec), $ws.Cells.Item($last + 10, $ec)).Borders.Color = 0xBFBFBF
    }
    $ws.Activate()
    $ws.Application.ActiveWindow.SplitRow = $r0
    $ws.Application.ActiveWindow.FreezePanes = $true
    try {   # 沒有印表機時 PageSetup 會丟例外，略過即可
        $ws.PageSetup.Orientation = 2        # 橫向
        $ws.PageSetup.Zoom = $false
        $ws.PageSetup.FitToPagesWide = 1
        $ws.PageSetup.FitToPagesTall = $false
    } catch { }
}

